#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# SQLite backup for BidTracker.
#
# WHY NOT `cp app.db backup.db`?
# Because the database runs in WAL mode. At any moment, committed transactions
# may live in app.db-wal and not yet in app.db. Copying only the main file gives
# you a torn, older snapshot; copying all three files while a write is in flight
# gives you a corrupt one.
#
# `VACUUM INTO` (SQLite >= 3.27) takes a read lock, writes a fully-checkpointed,
# defragmented copy to a new file, and never blocks writers. That single file is
# a complete, consistent, immediately-usable database. It is the right primitive
# here, so it is what this script uses, with `.backup` as the fallback.
#
# USAGE
#   ./scripts/backup.sh                     # back up the running container's DB
#   ./scripts/backup.sh /path/to/app.db     # back up a specific file
#
# ENVIRONMENT
#   BACKUP_DIR   where to write        (default ./backups)
#   KEEP_DAILY   daily copies to keep  (default 14)
#   KEEP_WEEKLY  Sunday copies to keep (default 8)
#   CONTAINER    backend container     (default bidtracker-backend)
#
# CRON (daily 03:15, log to syslog):
#   15 3 * * * cd /srv/bidtracker && ./scripts/backup.sh 2>&1 | logger -t bidtracker-backup
# ---------------------------------------------------------------------------
set -euo pipefail

BACKUP_DIR="${BACKUP_DIR:-$(cd "$(dirname "$0")/.." && pwd)/backups}"
KEEP_DAILY="${KEEP_DAILY:-14}"
KEEP_WEEKLY="${KEEP_WEEKLY:-8}"
CONTAINER="${CONTAINER:-bidtracker-backend}"
SOURCE_DB="${1:-}"

STAMP="$(date -u +%Y%m%d-%H%M%S)"
DOW="$(date -u +%u)"          # 7 = Sunday
mkdir -p "$BACKUP_DIR/daily" "$BACKUP_DIR/weekly"

TARGET="$BACKUP_DIR/daily/app-$STAMP.db"

log() { printf '[backup] %s\n' "$*"; }

# ---------------------------------------------------------------------------
# 1. Produce a consistent copy.
# ---------------------------------------------------------------------------
if [ -n "$SOURCE_DB" ]; then
  # --- direct file mode (host has sqlite3 installed) ---
  command -v sqlite3 >/dev/null 2>&1 || {
    log "ERROR: sqlite3 is required for direct-file mode"
    exit 1
  }
  log "VACUUM INTO from $SOURCE_DB"
  sqlite3 "$SOURCE_DB" "VACUUM INTO '$TARGET';"

elif docker ps --format '{{.Names}}' | grep -qx "$CONTAINER"; then
  # --- container mode (the normal path) ---
  # The image has no sqlite3 CLI, so the copy is made through Prisma's bundled
  # SQLite via $queryRawUnsafe. Interpolating a variable into SQL is acceptable
  # here only because the value is generated by this script, not user input.
  log "VACUUM INTO inside $CONTAINER"
  docker exec "$CONTAINER" node -e "
    const { PrismaClient } = require('@prisma/client');
    const p = new PrismaClient();
    p.\$queryRawUnsafe(\"VACUUM INTO '/data/backup-tmp.db'\")
      .then(() => p.\$disconnect())
      .then(() => process.exit(0))
      .catch((e) => { console.error(e.message); process.exit(1); });
  "
  docker cp "$CONTAINER:/data/backup-tmp.db" "$TARGET"
  docker exec "$CONTAINER" rm -f /data/backup-tmp.db

else
  log "ERROR: container '$CONTAINER' is not running and no source file was given."
  log "       Pass a path:  $0 /var/lib/docker/volumes/…/app.db"
  exit 1
fi

# ---------------------------------------------------------------------------
# 2. Verify before trusting it. An unverified backup is a rumour.
# ---------------------------------------------------------------------------
if command -v sqlite3 >/dev/null 2>&1; then
  RESULT="$(sqlite3 "$TARGET" 'PRAGMA integrity_check;' || echo failed)"
  if [ "$RESULT" != "ok" ]; then
    log "ERROR: integrity_check on $TARGET returned: $RESULT"
    mv "$TARGET" "$TARGET.CORRUPT"
    exit 1
  fi
  ROWS="$(sqlite3 "$TARGET" 'SELECT COUNT(*) FROM job_applications;')"
  log "integrity ok · $ROWS applications"
else
  log "note: sqlite3 not installed on the host — skipping integrity_check"
fi

gzip -9 "$TARGET"
TARGET="$TARGET.gz"
log "wrote $TARGET ($(du -h "$TARGET" | cut -f1))"

# ---------------------------------------------------------------------------
# 3. Retention. Sunday copies are promoted to the weekly set.
# ---------------------------------------------------------------------------
if [ "$DOW" = "7" ]; then
  cp "$TARGET" "$BACKUP_DIR/weekly/"
  log "promoted to weekly"
fi

prune() {
  local dir="$1" keep="$2"
  local count
  count="$(find "$dir" -name 'app-*.db.gz' | wc -l | tr -d ' ')"
  if [ "$count" -gt "$keep" ]; then
    find "$dir" -name 'app-*.db.gz' -print0 \
      | xargs -0 ls -1t \
      | tail -n +"$((keep + 1))" \
      | while read -r old; do
          log "pruning $(basename "$old")"
          rm -f "$old"
        done
  fi
}

prune "$BACKUP_DIR/daily" "$KEEP_DAILY"
prune "$BACKUP_DIR/weekly" "$KEEP_WEEKLY"

log "done"

# ---------------------------------------------------------------------------
# RESTORE
#   docker compose stop backend
#   gunzip -c backups/daily/app-20260825-031500.db.gz > /tmp/app.db
#   docker run --rm -v bidtracker-data:/data -v /tmp:/in alpine \
#     sh -c 'rm -f /data/app.db-wal /data/app.db-shm && cp /in/app.db /data/app.db'
#   docker compose start backend
#
# Deleting the stale -wal/-shm files matters: leaving them beside a restored
# database makes SQLite try to replay a log that belongs to a different file.
# ---------------------------------------------------------------------------
